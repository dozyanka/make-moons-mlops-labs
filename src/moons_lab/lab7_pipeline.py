"""LAB7: bounded sliding windows, real prediction API, and drift drills.

A 1000-row window with step=500 retains at most 1000 samples; each newly
received block is generated by the deterministic LAB5 generator.  Metrics
are evaluated on predictions returned by the LAB6 FastAPI endpoint.
"""
from __future__ import annotations

from collections import deque
from typing import Callable

import numpy as np
import pandas as pd

from .config import Lab7Config
from .drift import compute_drift
from .generator import GeneratorSettings, generate_dataframe


SCENARIOS = ("clean", "mean_shift", "class_ratio_shift")


def drifting_settings(cfg: Lab7Config, scenario: str, step_no: int) -> GeneratorSettings:
    if scenario not in SCENARIOS:
        raise ValueError(f"unknown stream scenario {scenario}")
    payload = {
        "mode": "similar", "n_samples": cfg.window_size if step_no == 0 else cfg.window_step,
        "seed": cfg.seed + 100 + step_no,
        "noise": 0.22,
    }
    if step_no >= cfg.drift_start_window:
        if scenario == "mean_shift":
            payload.update(shift_x=cfg.drift_shift_x, shift_y=cfg.drift_shift_y)
        elif scenario == "class_ratio_shift":
            payload.update(class_1_ratio=cfg.drift_class_ratio)
    return GeneratorSettings(**payload)


def assess_window(reference: pd.DataFrame, window: pd.DataFrame, reference_p: np.ndarray,
                  predicted: np.ndarray, *, scenario: str, index: int,
                  drift_fraction: float, cfg: Lab7Config) -> dict:
    if len(window) != cfg.window_size or len(predicted) != len(window):
        raise ValueError("window/predictions length mismatch")
    scores = compute_drift(
        reference[["x1", "x2"]].to_numpy(), window[["x1", "x2"]].to_numpy(),
        reference_p, predicted,
    )
    input_alert = bool(scores.max_feature_psi > cfg.psi_alert_threshold)
    prediction_alert = bool(scores.csi_prediction > cfg.csi_alert_threshold)
    return {
        "scenario": scenario, "window": index, "start_row": index * cfg.window_step,
        "end_row_exclusive": index * cfg.window_step + cfg.window_size,
        "injected_drift": bool(drift_fraction > 0),
        "drift_fraction": float(drift_fraction),
        "psi_x1": scores.psi_x1, "psi_x2": scores.psi_x2,
        "ks_x1": scores.ks_x1, "ks_x2": scores.ks_x2,
        "csi_prediction": scores.csi_prediction,
        "input_alert": input_alert, "prediction_alert": prediction_alert,
        "alert": input_alert or prediction_alert,
    }


def collect_window_metrics(cfg: Lab7Config, scenario: str, reference: pd.DataFrame,
                           predict_probabilities: Callable[[pd.DataFrame], np.ndarray],
                           on_window: Callable[[str, int, pd.DataFrame], dict] | None = None) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Return per-window metrics and the *last* full window for Evidently.

    The left side of each window is dropped after an increment.  We retain
    only W rows, not the whole generated stream.  The first drift arrives in
    the increment that creates window cfg.drift_start_window.
    """
    reference_p = np.asarray(predict_probabilities(reference), dtype=float)
    if reference_p.shape != (len(reference),):
        raise ValueError("predictor returned wrong reference probabilities shape")
    rows: deque[tuple[float, float, bool]] = deque(maxlen=cfg.window_size)
    records: list[dict] = []
    last: pd.DataFrame | None = None
    for window_index in range(cfg.n_windows):
        block = generate_dataframe(drifting_settings(cfg, scenario, window_index))
        changed = scenario != "clean" and window_index >= cfg.drift_start_window
        for entry in block[["x1", "x2"]].itertuples(index=False, name=None):
            rows.append((float(entry[0]), float(entry[1]), changed))
        if len(rows) != cfg.window_size:
            raise AssertionError("sliding window has wrong size")
        frame = pd.DataFrame(rows, columns=["x1", "x2", "changed"])
        fraction = float(frame["changed"].mean())
        sample = frame[["x1", "x2"]].copy()
        predictions = np.asarray(predict_probabilities(sample), dtype=float)
        record = assess_window(
            reference, sample, reference_p, predictions,
            scenario=scenario, index=window_index, drift_fraction=fraction, cfg=cfg,
        )
        sample["probability"] = predictions
        if on_window is not None:
            record.update(on_window(scenario, window_index, sample))
        records.append(record)
        last = sample
    assert last is not None
    return pd.DataFrame(records), last


def summarize_drill(metrics: pd.DataFrame, scenario: str, cfg: Lab7Config) -> dict:
    base = metrics.loc[metrics["window"] < cfg.drift_start_window]
    false_alerts = int(base["alert"].sum())
    if scenario == "clean":
        first = None
        false_alerts = int(metrics["alert"].sum())
        passed = false_alerts <= cfg.max_clean_false_alerts
        detection_delay = None
    else:
        post = metrics.loc[(metrics["window"] >= cfg.drift_start_window) & metrics["alert"]]
        first = int(post["window"].min()) if not post.empty else None
        detection_delay = first - cfg.drift_start_window if first is not None else None
        passed = (
            first is not None and detection_delay <= cfg.detection_deadline_windows
            and false_alerts <= cfg.max_clean_false_alerts
        )
    return {
        "scenario": scenario,
        "first_drift_window": cfg.drift_start_window if scenario != "clean" else None,
        "first_alert_window": first,
        "detection_delay_windows": detection_delay,
        "deadline_windows": cfg.detection_deadline_windows if scenario != "clean" else None,
        "false_alerts": false_alerts,
        "accepted": bool(passed),
    }
